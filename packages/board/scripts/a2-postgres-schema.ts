// Writes src/store/a2-postgres-schema.ts: the schema.sql of the A2 release board depends on, as a
// module, so postgres() applies it wherever it's bundled. Run it after bumping experimental-a2;
// test/postgres-schema.test.ts fails until it matches.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const a2 = dirname(createRequire(import.meta.url).resolve('experimental-a2/package.json'))
const { version } = JSON.parse(readFileSync(join(a2, 'package.json'), 'utf8')) as { version: string }
const schema = readFileSync(join(a2, 'sql', 'postgres', 'schema.sql'), 'utf8')
writeFileSync(
  join(root, 'src', 'store', 'a2-postgres-schema.ts'),
  `// Generated by scripts/a2-postgres-schema.ts from experimental-a2@${version}'s sql/postgres/schema.sql: don't edit.\n` +
    `export const A2_POSTGRES_SCHEMA = ${JSON.stringify(schema)}\n`,
)
